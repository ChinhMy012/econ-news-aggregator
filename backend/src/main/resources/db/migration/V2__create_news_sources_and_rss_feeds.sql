CREATE TABLE news_sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(50) NOT NULL UNIQUE CHECK(code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 name VARCHAR(200) NOT NULL CHECK(btrim(name)<>''), website_url VARCHAR(2048) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rss_feeds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_id BIGINT NOT NULL REFERENCES news_sources(id) ON DELETE RESTRICT,
 name VARCHAR(200) NOT NULL CHECK(btrim(name)<>''), url VARCHAR(2048) NOT NULL UNIQUE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rss_feeds_source_id_id ON rss_feeds(source_id,id);
